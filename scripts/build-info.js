import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CACHE_DIR = path.join(ROOT, '.cache');
const META_FILE = path.join(CACHE_DIR, 'build-meta.json');
const FUNCTIONS_BUILD_FILE = path.join(ROOT, 'functions', '_shared', 'build.js');

const pad = (value) => String(value).padStart(2, '0');

const gitShortSha = () => {
  try {
    return execFileSync('git', ['rev-parse', '--short=7', 'HEAD'], {
      cwd: ROOT,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return 'local';
  }
};

const commitSha = () => {
  const fromCloudflare = (process.env.CF_PAGES_COMMIT_SHA || '').trim();
  if (fromCloudflare) return fromCloudflare.slice(0, 7);
  return gitShortSha();
};

/**
 * A build id is deliberately opaque to the browser. The timestamp makes two
 * deploys of the same commit distinguishable, while the commit prefix keeps the
 * id readable in logs and response headers.
 */
export function createBuildInfo({ dev = false } = {}) {
  const now = new Date();
  const date = `${now.getUTCFullYear()}-${pad(now.getUTCMonth() + 1)}-${pad(now.getUTCDate())}`;
  const time = `${pad(now.getUTCHours())}${pad(now.getUTCMinutes())}${pad(now.getUTCSeconds())}`;
  const entropy = crypto.randomBytes(2).toString('hex');
  const id = dev
    ? `dev-${date}-${time}-${entropy}`
    : `${date}-${commitSha()}-${time}-${entropy}`;

  const info = {
    id,
    commit: commitSha(),
    generatedAt: now.toISOString(),
    dev,
  };

  fs.mkdirSync(CACHE_DIR, { recursive: true });
  fs.writeFileSync(META_FILE, `${JSON.stringify(info, null, 2)}\n`);
  return info;
}

export function readBuildInfo({ dev = false } = {}) {
  try {
    const info = JSON.parse(fs.readFileSync(META_FILE, 'utf8'));
    if (info && typeof info.id === 'string' && info.id) return info;
  } catch {
    // The build id file is generated by prepare-build.js. Fall back to creating
    // one so direct Eleventy runs still work.
  }
  return createBuildInfo({ dev });
}

export function writeFunctionsBuildModule(info) {
  fs.mkdirSync(path.dirname(FUNCTIONS_BUILD_FILE), { recursive: true });
  fs.writeFileSync(
    FUNCTIONS_BUILD_FILE,
    [
      '// Generated by scripts/prepare-build.js. Do not edit by hand.',
      `export const BUILD_ID = ${JSON.stringify(info.id)};`,
      `export const BUILD_GENERATED_AT = ${JSON.stringify(info.generatedAt)};`,
      '',
    ].join('\n'),
  );
}

export { ROOT, CACHE_DIR, META_FILE, FUNCTIONS_BUILD_FILE };
